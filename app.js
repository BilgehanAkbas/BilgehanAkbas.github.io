/* V12: definitive chat launcher motion.
   Uses requestAnimationFrame so CSS cascade / !important / reduced-motion
   settings cannot cancel the requested movement. */
(function startChatLauncherFloat(){
  const wrap=document.getElementById("chatFloatWrap");
  if(!wrap) return;

  let paused=false;
  let start=performance.now();
  const amplitude=6;       // px
  const period=2800;       // ms, slow/subtle

  wrap.addEventListener("mouseenter",()=>paused=true);
  wrap.addEventListener("mouseleave",()=>{
    paused=false;
    start=performance.now();
  });

  function frame(now){
    if(!paused && wrap.style.display!=="none"){
      const phase=((now-start)%period)/period;
      const y=-Math.sin(phase*Math.PI*2)*amplitude;
      wrap.style.transform=`translate3d(0,${y.toFixed(2)}px,0)`;
    }else if(paused){
      wrap.style.transform="translate3d(0,0,0)";
    }
    requestAnimationFrame(frame);
  }
  requestAnimationFrame(frame);
})();

