function updateScrollUI(){
  const doc=document.documentElement;
  const max=Math.max(1,doc.scrollHeight-window.innerHeight);
  const progress=Math.min(1,Math.max(0,window.scrollY/max));
  if(scrollProgressBar) scrollProgressBar.style.transform=`scaleX(${progress})`;

  if(backToTop) backToTop.classList.toggle("visible",window.scrollY>520);

  let current=null;
  const marker=window.scrollY+Math.max(110,parseInt(getComputedStyle(doc).getPropertyValue("--nav-h"))+70);
  navSections.forEach(section=>{
    if(section.offsetTop<=marker) current=section.id;
  });
  navSectionLinks.forEach(a=>a.classList.toggle("active",a.getAttribute("href")==="#"+current));
}
