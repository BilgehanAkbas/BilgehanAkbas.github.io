async function sendMessage(text){
  text=(text||"").trim();
  if(!text)return;

  const now=Date.now();
  const normalized=normalizeChatText(text);

  if(now-lastSendAt<700){
    addMessage("assistant",currentLang==="tr"
      ?"Bir saniye 😄 Mesajları biraz daha yavaş gönderirsen daha sağlıklı cevap verebilirim."
      :"One second 😄 Send messages a little slower so I can respond properly.");
    return;
  }

  if(isLowSignalSpam(normalized)){
    addMessage("user",text);
    chatInput.value="";
    addMessage("assistant",currentLang==="tr"
      ?"Mesajı gördüm 😄 Bana projelerim, deneyimlerim ya da kullandığım teknolojilerle ilgili bir şey sorabilirsin."
      :"I saw your message 😄 You can ask me about my projects, experience or the technologies I use.");
    lastSendAt=now;
    return;
  }

  if(normalized===lastUserMessage && now-lastUserMessageAt<15000){
    repeatCount++;
    lastUserMessageAt=now;
    addMessage("user",text);
    chatInput.value="";
    addMessage("assistant",currentLang==="tr"
      ?(repeatCount===1
        ?"Aynı mesajı tekrar gördüm 😄 Başka bir şey sorarsan oradan devam edelim."
        :"Bunu tekrar backend'e göndermiyorum 🙂 Farklı bir soru yazabilirsin.")
      :(repeatCount===1
        ?"I saw the same message again 😄 Ask something else and we can continue from there."
        :"I won't send the same message to the backend again 🙂 Try a different question."));
    return;
  }

  lastUserMessage=normalized;
  lastUserMessageAt=now;
  repeatCount=0;
  lastSendAt=now;

  addMessage("user",text);
  conversation.push({role:"user",content:text});
  conversation=conversation.slice(-10);
  chatInput.value="";
  chatQuickReplies.innerHTML="";

  try{
    const res=await fetch("https://kisiselai.bilgehanakbas0.workers.dev/",{
      method:"POST",
      headers:{"Content-Type":"application/json"},
      body:JSON.stringify({messages:conversation})
    });
    const data=await res.json();
    const reply=data.reply||LANG[currentLang].conn_error+(data.error||"");
    addMessage("assistant",reply);
    if(data.reply){
      conversation.push({role:"assistant",content:data.reply});
      conversation=conversation.slice(-10);
    }
  }catch(err){
    addMessage("assistant",LANG[currentLang].conn_error+err.message);
  }
}
